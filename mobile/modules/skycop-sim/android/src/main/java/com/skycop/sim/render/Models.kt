    /** A thin four-sided rod between two points: pillars, rails, spokes and arms. */
    private fun MeshBuilder.rod(ax: Float, ay: Float, az: Float, bx: Float, by: Float, bz: Float, r: Float, color: Int, material: Int) {
        val dx = bx - ax; val dy = by - ay; val dz = bz - az
        val length = sqrt(dx * dx + dy * dy + dz * dz)
        if (length < 1e-5f) return
        // Two axes across the rod, picked away from its own direction.
        var ux: Float; var uy: Float; var uz: Float
        if (abs(dy) < 0.9f * length) { ux = dz; uy = 0f; uz = -dx } else { ux = 0f; uy = -dz; uz = dy }
        val u = sqrt(ux * ux + uy * uy + uz * uz); ux = ux / u * r; uy = uy / u * r; uz = uz / u * r
        var vx = dy * uz - dz * uy; var vy = dz * ux - dx * uz; var vz = dx * uy - dy * ux
        val v = sqrt(vx * vx + vy * vy + vz * vz); vx = vx / v * r; vy = vy / v * r; vz = vz / v * r
        val cx = floatArrayOf(ux, vx, -ux, -vx); val cy = floatArrayOf(uy, vy, -uy, -vy); val cz = floatArrayOf(uz, vz, -uz, -vz)
        for (k in 0..3) {
            val n = (k + 1) % 4
            quad(ax + cx[k], ay + cy[k], az + cz[k], ax + cx[n], ay + cy[n], az + cz[n],
                bx + cx[n], by + cy[n], bz + cz[n], bx + cx[k], by + cy[k], bz + cz[k], color, material)
        }
    }

    /** The dark wheel well: a half disc on the body side, facing out along [side]. */
    private fun MeshBuilder.arch(x: Float, y: Float, z: Float, r: Float, side: Float, color: Int) {
        for (i in 0 until 8) {
            val a = i * PI_F / 8; val b = (i + 1) * PI_F / 8
            val az = z + cos(a) * r; val ay = y + sin(a) * r; val bz = z + cos(b) * r; val by = y + sin(b) * r
            if (side > 0f) triangle(x, y, z, x, ay, az, x, by, bz, color) else triangle(x, y, z, x, by, bz, x, ay, az, color)
        }
    }

    /** Windscreen, side and rear glass with pillars, sills and a crowned roof. */
    private fun MeshBuilder.glasshouse(w0: Float, w1: Float, y0: Float, y1: Float, f0: Float, f1: Float, b0: Float, b1: Float) {
        quad(-w0, y0, f0, -w1, y1, f1, w1, y1, f1, w0, y0, f0, WINDOW, Mat.GLASS)
        quad(-w0, y0, b0, w0, y0, b0, w1, y1, b1, -w1, y1, b1, WINDOW, Mat.GLASS)
        quad(w0, y0, b0, w0, y0, f0, w1, y1, f1, w1, y1, b1, WINDOW, Mat.GLASS)
        quad(-w0, y0, f0, -w0, y0, b0, -w1, y1, b1, -w1, y1, f1, WINDOW, Mat.GLASS)
        val crown = y1 + 0.04f
        quad(-w1, y1, b1, 0f, crown, b1, 0f, crown, f1, -w1, y1, f1, TINTED, Mat.TINT)
        quad(0f, crown, b1, w1, y1, b1, w1, y1, f1, 0f, crown, f1, TINTED, Mat.TINT)
        for (s in floatArrayOf(-1f, 1f)) {
            rod(s * w0, y0, f0, s * w1, y1, f1, 0.035f, TINTED, Mat.TINT)
            rod(s * w0, y0, b0, s * w1, y1, b1, 0.07f, TINTED, Mat.TINT)
            rod(s * w1, y1, f1, s * w1, y1, b1, 0.03f, TINTED, Mat.TINT)
            val middle = (f0 + b0) / 2 - 0.1f
            rod(s * w0, y0, middle, s * w1, y1, middle + (f1 + b1 - f0 - b0) / 2, 0.045f, 0x1C1F22, Mat.PLAIN)
        }
    }

