  /// A thin four-sided rod between two points: pillars, rails, spokes and arms.
  private static func rod(_ m: MeshBuilder, _ ax: Float, _ ay: Float, _ az: Float, _ bx: Float, _ by: Float, _ bz: Float, _ r: Float, _ color: Int, _ material: Int) {
    let dx = bx - ax, dy = by - ay, dz = bz - az
    let length = sqrt(dx * dx + dy * dy + dz * dz)
    if length < 1e-5 { return }
    var ux: Float, uy: Float, uz: Float
    if abs(dy) < 0.9 * length { ux = dz; uy = 0; uz = -dx } else { ux = 0; uy = -dz; uz = dy }
    let u = sqrt(ux * ux + uy * uy + uz * uz); ux = ux / u * r; uy = uy / u * r; uz = uz / u * r
    var vx = dy * uz - dz * uy, vy = dz * ux - dx * uz, vz = dx * uy - dy * ux
    let v = sqrt(vx * vx + vy * vy + vz * vz); vx = vx / v * r; vy = vy / v * r; vz = vz / v * r
    let cx = [ux, vx, -ux, -vx], cy = [uy, vy, -uy, -vy], cz = [uz, vz, -uz, -vz]
    for k in 0...3 {
      let n = (k + 1) % 4
      m.quad(ax + cx[k], ay + cy[k], az + cz[k], ax + cx[n], ay + cy[n], az + cz[n],
             bx + cx[n], by + cy[n], bz + cz[n], bx + cx[k], by + cy[k], bz + cz[k], color, material)
    }
  }

  /// The dark wheel well: a half disc on the body side, facing out along `side`.
  private static func arch(_ m: MeshBuilder, _ x: Float, _ y: Float, _ z: Float, _ r: Float, _ side: Float, _ color: Int) {
    for i in 0..<8 {
      let a = Float(i) * PI_F / 8, b = Float(i + 1) * PI_F / 8
      let az = z + cos(a) * r, ay = y + sin(a) * r, bz = z + cos(b) * r, by = y + sin(b) * r
      if side > 0 { m.triangle(x, y, z, x, ay, az, x, by, bz, color) } else { m.triangle(x, y, z, x, by, bz, x, ay, az, color) }
    }
  }

  /// Windscreen, side and rear glass with pillars, sills and a crowned roof.
  private static func glasshouse(_ m: MeshBuilder, _ w0: Float, _ w1: Float, _ y0: Float, _ y1: Float, _ f0: Float, _ f1: Float, _ b0: Float, _ b1: Float) {
    m.quad(-w0, y0, f0, -w1, y1, f1, w1, y1, f1, w0, y0, f0, WINDOW, Mat.GLASS)
